let current;

function resolveLanguage() {
  if (current) {
    return current;
  }
  let language = 'en';
  try {
    language = require('vscode').env.language || 'en';
  } catch {
    language = 'en';
  }
  current = language.startsWith('zh') ? zh : en;
  return current;
}

function t(key, ...args) {
  let text = resolveLanguage()[key] ?? en[key] ?? key;
  args.forEach((value, index) => {
    text = text.replaceAll(`{${index}}`, String(value));
  });
  return text;
}

module.exports = { t };
